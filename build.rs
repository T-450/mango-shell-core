//! Converts the DTCG token files in `tokens/` into Rust constants (`$OUT_DIR/tokens.rs`): the
//! `Tokens` struct with one colour per key in `KEYS`, its dark and light defaults, and every
//! number, dimension, weight and motion token. A missing or malformed token fails the build.

use std::fmt::Write as _;
use std::io::Write as _;
use std::path::PathBuf;
use std::{fs, io};

use serde_json::Value;

/// The colour tokens components draw with, as DTCG paths under `color.`.
const KEYS: [&str; 15] = [
    "bg.bar",
    "bg.raised",
    "line.hairline",
    "line.strong",
    "text.primary",
    "text.secondary",
    "text.tertiary",
    "selection",
    "text.on-selection",
    "accent.signal",
    "accent.focus",
    "status.ok",
    "status.warn",
    "status.critical",
    "signal.empty",
];

const DARK: &str = "tokens/dark-2026-fui.tokens.json";
const LIGHT: &str = "tokens/light-2026-fui.tokens.json";

fn main() -> Result<(), String> {
    let out = std::env::var_os("OUT_DIR").ok_or("OUT_DIR is not set")?;
    let mut stdout = io::stdout();
    for path in [DARK, LIGHT] {
        writeln!(stdout, "cargo::rerun-if-changed={path}").map_err(|e| e.to_string())?;
    }
    let dark = read(DARK)?;
    let light = read(LIGHT)?;

    let mut src =
        String::from("// Generated by build.rs from tokens/*.tokens.json. Do not edit.\n\n");
    write_struct(&mut src);
    write_colors(&mut src, "DARK", "dark", &dark)?;
    write_colors(&mut src, "LIGHT", "light", &light)?;
    write_numbers(&mut src, &dark, "")?;

    fs::write(PathBuf::from(out).join("tokens.rs"), src)
        .map_err(|e| format!("write tokens.rs: {e}"))
}

fn read(path: &str) -> Result<Value, String> {
    let src = fs::read_to_string(path).map_err(|e| format!("{path}: {e}"))?;
    serde_json::from_str(&src).map_err(|e| format!("{path}: {e}"))
}

fn field(key: &str) -> String {
    key.replace(['.', '-'], "_")
}

fn write_struct(src: &mut String) {
    src.push_str("/// One resolved colour per design token.\n");
    src.push_str("#[derive(Clone, Debug, PartialEq)]\npub struct Tokens {\n");
    for key in KEYS {
        let _ = writeln!(src, "    /// `{key}`\n    pub {}: Color,", field(key));
    }
    src.push_str("    /// Whether these are dark-variant tokens.\n    pub dark: bool,\n}\n\n");
    src.push_str("/// Every token key, as a theme file names it.\n");
    let _ = writeln!(src, "pub const KEYS: [&str; {}] = {KEYS:?};\n", KEYS.len());
    src.push_str("impl Tokens {\n");
    src.push_str("    /// Reads every key from `theme`, naming the first one missing.\n");
    src.push_str(
        "    pub(crate) fn from_theme(theme: &rune::theme::Theme) -> Result<Tokens, String> {\n",
    );
    src.push_str("        let get = |key: &str| theme.try_color(key).ok_or_else(|| format!(\"missing token {key:?}\"));\n");
    src.push_str("        Ok(Tokens {\n");
    for key in KEYS {
        let _ = writeln!(src, "            {}: get({key:?})?,", field(key));
    }
    src.push_str("            dark: theme.dark,\n        })\n    }\n}\n\n");
}

fn write_colors(src: &mut String, name: &str, variant: &str, tokens: &Value) -> Result<(), String> {
    let _ = writeln!(src, "/// The built-in {variant} tokens.");
    let _ = writeln!(src, "pub const {name}: Tokens = Tokens {{");
    for key in KEYS {
        let path = format!("color.{key}");
        let hex = lookup(tokens, &path)?
            .get("hex")
            .and_then(Value::as_str)
            .ok_or_else(|| format!("{variant}: {path} has no hex value"))?;
        let [r, g, b] = linear(hex).ok_or_else(|| format!("{variant}: {path}: bad hex {hex:?}"))?;
        let _ = writeln!(
            src,
            "    {}: Color {{ r: {}, g: {}, b: {}, a: 1.0 }},",
            field(key),
            lit(r),
            lit(g),
            lit(b),
        );
    }
    let _ = writeln!(src, "    dark: {},\n}};\n", variant == "dark");
    Ok(())
}

fn lookup<'a>(tokens: &'a Value, path: &str) -> Result<&'a Value, String> {
    path.split('.')
        .try_fold(tokens, |node, part| node.get(part))
        .and_then(|node| node.get("$value"))
        .ok_or_else(|| format!("missing token {path}"))
}

/// `#rrggbb` to linear sRGB, as `rune::color::hex` decodes it.
fn linear(hex: &str) -> Option<[f32; 3]> {
    let h = hex.strip_prefix('#').filter(|h| h.len() == 6)?;
    let channel = |i: usize| {
        let v = f32::from(u8::from_str_radix(h.get(i..i + 2)?, 16).ok()?) / 255.0;
        Some(if v <= 0.040_45 {
            v / 12.92
        } else {
            ((v + 0.055) / 1.055).powf(2.4)
        })
    };
    Some([channel(0)?, channel(2)?, channel(4)?])
}

/// `v` as a Rust literal with its fraction grouped in threes, as clippy's `unreadable_literal`
/// asks of hand-written code.
fn lit(v: f32) -> String {
    let text = format!("{v:?}");
    let Some((whole, fraction)) = text.split_once('.') else {
        return text;
    };
    let groups: Vec<&str> = fraction
        .as_bytes()
        .chunks(3)
        .filter_map(|c| std::str::from_utf8(c).ok())
        .collect();
    format!("{whole}.{}", groups.join("_"))
}

/// Every non-colour token, named by its path in upper snake case: numbers, weights and pixel
/// dimensions as `f32`, durations as springs.
fn write_numbers(src: &mut String, node: &Value, path: &str) -> Result<(), String> {
    let Some(map) = node.as_object() else {
        return Ok(());
    };
    if let Some(value) = map.get("$value") {
        let kind = map.get("$type").and_then(Value::as_str).unwrap_or_default();
        let name = path.to_uppercase().replace(['.', '-'], "_");
        let number = |v: &Value| {
            serde_json::from_value::<f32>(v.clone()).map_err(|e| format!("{path}: {e}"))
        };
        match kind {
            "number" | "fontWeight" => {
                let _ = writeln!(
                    src,
                    "/// `{path}`\npub const {name}: f32 = {:?};",
                    number(value)?
                );
            }
            "dimension" => {
                let v = value
                    .get("value")
                    .ok_or_else(|| format!("{path}: no value"))?;
                let _ = writeln!(
                    src,
                    "/// `{path}` in pixels\npub const {name}: f32 = {:?};",
                    number(v)?
                );
            }
            "duration" => {
                let v = value
                    .get("value")
                    .ok_or_else(|| format!("{path}: no value"))?;
                let _ = writeln!(
                    src,
                    "/// `{path}`\npub const {name}: Spring = Spring::new({:?}, {:?});",
                    number(v)?,
                    bounce(path),
                );
            }
            _ => {}
        }
        return Ok(());
    }
    for (key, child) in map
        .iter()
        .filter(|(key, _)| !key.starts_with('$') && key.as_str() != "color")
    {
        let child_path = if path.is_empty() {
            key.clone()
        } else {
            format!("{path}.{key}")
        };
        write_numbers(src, child, &child_path)?;
    }
    Ok(())
}

/// `docs/DESIGN-SYSTEM.md`, "Motion": spatial springs overshoot slightly, the hero more, effects
/// not at all.
fn bounce(path: &str) -> f32 {
    match path {
        "motion.spatial-hero" => 0.20,
        p if p.starts_with("motion.spatial") => 0.10,
        _ => 0.0,
    }
}
